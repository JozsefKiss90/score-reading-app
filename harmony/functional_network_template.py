TEMPLATES = {
    "functional_degree_network_v1": functional_degree_network_v1,
    "functional_degree_network_minor_v2": functional_degree_network_minor_v2,
}

DEFAULT_TEMPLATE_ID = "functional_degree_network_v1"


def get_template(template_id: Optional[str] = None) -> FunctionalNetworkTemplate:
    """Return a validated functional template by id (default: the v1 journey)."""
    tid = template_id or DEFAULT_TEMPLATE_ID
    if tid not in TEMPLATES:
        raise KeyError(
            f"unknown functional template {tid!r}; available: {sorted(TEMPLATES)}")
    tpl = TEMPLATES[tid]()
    tpl.validate()
    return tpl


def load_template(data: Dict) -> FunctionalNetworkTemplate:
    """Load (and validate) a functional template from a serialised dict."""
    return FunctionalNetworkTemplate.from_dict(data)
