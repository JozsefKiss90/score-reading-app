"""Topological templates for the Functional Degree Network.

The **Functional Degree Network** is the practice-first sibling of the
Harmonic Network / Tonal Graph layer (:mod:`harmony.network_template` /
:mod:`harmony.harmonic_network`).  Where the v1 network wires *whole keys*
(major / relative minor / V7 / vii°) together across the full circle of
fifths, this network makes **every diatonic degree of a few journey keys a
real graph node**, grouped by harmonic function (T / PD-S / D), and reveals
itself in guided stages driven by the Harmony Trainer
(:mod:`harmony.functional_journey`).

This module is the **schema** for that layer -- a deliberate *mirror* of
:mod:`harmony.network_template` with its own closed vocabularies.  The v1
vocabularies (``NODE_KINDS`` / ``ALL_RELATIONS``) are NOT widened: their
``validate()`` is a contract other tests rely on, so this module is a
parallel schema, not an extension (see docs/functional_network_plan.md §5).

A :class:`FunctionalNetworkTemplate` is a pure, serialisable description of:

* the node *classes* (diatonic degree triad / function group / key hub);
* the edge *classes* (functional relationship vocabulary: membership,
  resolution, preparation, substitution, deception, cross-key identity),
  split into implemented and reserved relations;
* the layout rules: one **panel per journey key** (panels ordered by fifths)
  with fixed functional positions inside the panel -- the T→PD→D→T cycle the
  eye can follow (PD/S column left, D column right, T cluster bottom-centre);
* which deterministic *generation rules* the builder should run;
* the launch rules (everything here is triad-based, so **every node is
  launchable** -- no reserved drills anywhere in this graph).

It deliberately contains **no theory tables**: the actual nodes/edges are
generated by :mod:`harmony.functional_network` from the live theory engine
(:mod:`theory.diatonic_harmony`).  This template graduates the audited
``core_triad_function_network_v1`` planned stub (and the staged-drill half of
``cadence_resolution_network_v1``) into one concrete, buildable topology.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional

# The dumb node/edge-class records are schema-agnostic; reuse them verbatim
# (all vocabulary validation lives on the template class below, so importing
# them cannot loosen the v1 module's contract).
from harmony.network_template import NodeClass, EdgeClass
# Display labels/badges come from the single function vocabulary (ticket 01 / plan F1); the
# closed schema vocabularies (NODE_KINDS / ALL_RELATIONS / FUNCTION_GROUPS keys) stay frozen.
from harmony.harmonic_roles import INTERNAL_FAMILY_SHORT, internal_family_label


SCHEMA_VERSION = "harmony-functional-network-template/v1"

# ---------------------------------------------------------------------------
# Controlled vocabularies (this schema's closed sets)
# ---------------------------------------------------------------------------

#: The three node classes of the functional degree network.
NODE_KINDS = [
    "degree_triad",       # one of the 7 diatonic triads of a journey key
    "function_group",     # a T / PD-S / D functional family within a key
    "key_hub",            # the journey key itself (one per panel)
]

#: Relationship vocabulary *implemented* by the functional graph builder.
IMPLEMENTED_RELATIONS = [
    "function_member",    # degree -> its function group (I -> T, ii -> PD/S)
    "resolves_to",        # dominant-function pull home (V -> I, vii° -> I)
    "prepares",           # predominant approach (ii -> V, IV -> V)
    "tonic_substitute",   # vi <-> I, iii <-> I (shared chord tones)
    "deceptive_to",       # the deceptive resolution V -> vi
    "shared_triad",       # pitch-class-identical triads across panels
    "fifth_relation",     # adjacent journey keys a perfect fifth apart
    "in_key",             # degree -> its key hub (panel membership overlay)
]

#: Relationship vocabulary *reserved* (named now, generated by a future layer).
RESERVED_RELATIONS = [
    "modulation_path_to",
    "borrowed_from_parallel",
]

#: Every relation a template may legally name (implemented + reserved).
ALL_RELATIONS = IMPLEMENTED_RELATIONS + RESERVED_RELATIONS

#: The deterministic edge-generation passes the functional builder runs.
GENERATION_RULES = [
    "function_member_edges",   # 1. degree -> function group membership
    "resolution_edges",        # 2. V -> I, vii° -> I
    "preparation_edges",       # 3. ii -> V, IV -> V
    "substitute_edges",        # 4. vi <-> I, iii <-> I
    "deceptive_edges",         # 5. V -> vi
    "in_key_edges",            # 6. degree -> key hub (default-off overlay)
    "fifth_relation_edges",    # 7. adjacent panels by fifths
    "shared_triad_edges",      # 8. same pitch-class set across panels
]

#: The visual classes (node colours) of this network's palette.
VISUAL_CLASSES = ["emerald", "violet", "amber"]

#: The panel modes a functional template may declare.  ``minor`` panels use
#: the *harmonic* minor chord set (the real V / vii°, ticket 13 / G2a) while
#: the key context stays natural minor.  This is template metadata, not a
#: vocabulary widening: kinds/relations/rules above stay frozen.
PANEL_MODES = ["major", "minor"]

#: The three merged function groups (T / PD-S / D), in T->PD->D order.
#: The engine's five per-degree ``function_label`` values collapse onto these
#: (the builder owns that mapping); ``mediant`` is grouped as a tonic
#: substitute, with each node's explanation stating the ambiguity.
FUNCTION_GROUPS = ["tonic", "predominant", "dominant"]

#: Short badge / long display labels for the function groups -- derived from the shared
#: vocabulary (never hand-edit; ticket 01 / plan F1).
FUNCTION_GROUP_SHORT = {g: INTERNAL_FAMILY_SHORT[g] for g in FUNCTION_GROUPS}
FUNCTION_GROUP_LABELS = {g: internal_family_label(g) for g in FUNCTION_GROUPS}


# ---------------------------------------------------------------------------
# Schema dataclasses
# ---------------------------------------------------------------------------

@dataclass
class PanelLayoutRule:
    """How one node class is drawn inside a key panel (radius only -- the
    functional *positions* are template-level data shared by all panels)."""

    kind: str
    node_radius: float = 20.0
    description: str = ""

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass
class FunctionalNetworkTemplate:
    """A serialisable topological template for one functional degree network.

    Layout model: one panel per journey key, panels laid out left-to-right in
    circle-of-fifths order (the builder computes each panel's x-origin from
    ``panel_width``); inside a panel every degree / function group / hub has a
    fixed ``(dx, dy)`` offset.  All coordinates are computed in Python -- the
    JS renderer stays layout-free.
    """

    template_id: str
    title: str
    description: str
    node_classes: List[NodeClass]
    edge_classes: List[EdgeClass]
    layout_rules: List[PanelLayoutRule]
    generation_rules: List[str]
    #: The journey keys (major tonics) -- one panel each.  Display order is
    #: recomputed by fifths in the builder; this is the *pedagogical* order
    #: (C first: the journey starts there).
    journey_keys: List[str] = field(default_factory=list)
    #: Horizontal distance between adjacent panel centres.
    panel_width: float = 470.0
    #: Per-degree ``[dx, dy]`` offsets inside a panel, indexed 0..6 (I..vii°).
    #: PD/S column left, D column right, T cluster bottom-centre.
    degree_offsets: List[List[float]] = field(default_factory=list)
    #: Function-group ``[dx, dy]`` offsets, keyed by ``FUNCTION_GROUPS``.
    function_offsets: Dict[str, List[float]] = field(default_factory=dict)
    #: The key hub's ``[dx, dy]`` offset (top-centre of the panel).
    hub_offset: List[float] = field(default_factory=lambda: [0.0, -195.0])
    launch_rules: Dict[str, Any] = field(default_factory=dict)
    #: The panel mode: every journey key is a major key ("major") or a minor
    #: key ("minor", harmonic-minor chord set).  One journey = one mode; a
    #: mixed journey would need two templates.
    mode: str = "major"
    schema: str = SCHEMA_VERSION

    # -- lookups ---------------------------------------------------------
    def node_class(self, kind: str) -> NodeClass:
        for nc in self.node_classes:
            if nc.kind == kind:
                return nc
        raise KeyError(f"no node class for kind {kind!r}")

    def edge_class(self, relation: str) -> EdgeClass:
        for ec in self.edge_classes:
            if ec.relation == relation:
                return ec
        raise KeyError(f"no edge class for relation {relation!r}")

    def layout_for(self, kind: str) -> PanelLayoutRule:
        for lr in self.layout_rules:
            if lr.kind == kind:
                return lr
        raise KeyError(f"no layout rule for kind {kind!r}")

    def kinds(self) -> List[str]:
        return [nc.kind for nc in self.node_classes]

    def relations(self) -> List[str]:
        return [ec.relation for ec in self.edge_classes]

    def implemented_relations(self) -> List[str]:
        return [ec.relation for ec in self.edge_classes if ec.implemented]

    # -- validation ------------------------------------------------------
    def validate(self) -> None:
        """Raise :class:`ValueError` on any malformed / unknown-vocabulary field.

        Mirrors :meth:`harmony.network_template.HarmonicNetworkTemplate.validate`
        against *this* module's closed sets, plus the panel-layout invariants
        (7 degree offsets; one offset per function group; unique journey keys).
        """
        if not self.template_id:
            raise ValueError("template requires a non-empty template_id")
        if not self.title:
            raise ValueError("template requires a non-empty title")
        if not self.node_classes:
            raise ValueError("template requires at least one node class")
        if not self.edge_classes:
            raise ValueError("template requires at least one edge class")
        if not self.layout_rules:
            raise ValueError("template requires layout rules")

        seen_kinds = set()
        for nc in self.node_classes:
            if nc.kind not in NODE_KINDS:
                raise ValueError(
                    f"unknown node class {nc.kind!r}; expected one of {NODE_KINDS}")
            if nc.kind in seen_kinds:
                raise ValueError(f"duplicate node class {nc.kind!r}")
            seen_kinds.add(nc.kind)
            if nc.visual_class not in VISUAL_CLASSES:
                raise ValueError(
                    f"unknown visual class {nc.visual_class!r} for {nc.kind!r}; "
                    f"expected one of {VISUAL_CLASSES}")

        for ec in self.edge_classes:
            if ec.relation not in ALL_RELATIONS:
                raise ValueError(
                    f"unknown edge relation {ec.relation!r}; expected one of "
                    f"{ALL_RELATIONS}")
            if ec.relation in RESERVED_RELATIONS and ec.implemented:
                raise ValueError(
                    f"relation {ec.relation!r} is reserved and cannot be marked "
                    f"implemented")

        for rule in self.generation_rules:
            if rule not in GENERATION_RULES:
                raise ValueError(
                    f"unknown generation rule {rule!r}; expected one of "
                    f"{GENERATION_RULES}")

        layout_kinds = set()
        for lr in self.layout_rules:
            if lr.kind not in seen_kinds:
                raise ValueError(
                    f"layout rule for {lr.kind!r} has no matching node class")
            if lr.kind in layout_kinds:
                raise ValueError(f"duplicate layout rule for {lr.kind!r}")
            layout_kinds.add(lr.kind)
        missing = seen_kinds - layout_kinds
        if missing:
            raise ValueError(f"node classes missing a layout rule: {sorted(missing)}")

        if self.mode not in PANEL_MODES:
            raise ValueError(
                f"unknown panel mode {self.mode!r}; expected one of {PANEL_MODES}")

        if not self.journey_keys:
            raise ValueError("template requires at least one journey key")
        if len(set(self.journey_keys)) != len(self.journey_keys):
            raise ValueError(f"duplicate journey keys: {self.journey_keys}")

        if len(self.degree_offsets) != 7:
            raise ValueError(
                f"degree_offsets must cover the 7 diatonic degrees "
                f"(got {len(self.degree_offsets)})")
        for off in self.degree_offsets:
            if len(off) != 2:
                raise ValueError(f"degree offset {off!r} is not an [x, y] pair")
        if sorted(self.function_offsets) != sorted(FUNCTION_GROUPS):
            raise ValueError(
                f"function_offsets must be keyed exactly by {FUNCTION_GROUPS} "
                f"(got {sorted(self.function_offsets)})")
        for grp, off in self.function_offsets.items():
            if len(off) != 2:
                raise ValueError(f"function offset {grp}: {off!r} is not [x, y]")
        if len(self.hub_offset) != 2:
            raise ValueError(f"hub_offset {self.hub_offset!r} is not an [x, y] pair")
        if self.panel_width <= 0:
            raise ValueError("panel_width must be positive")

    # -- serialisation ---------------------------------------------------
    def to_dict(self) -> Dict:
        return {
            "schema": self.schema,
            "template_id": self.template_id,
            "title": self.title,
            "description": self.description,
            "node_classes": [nc.to_dict() for nc in self.node_classes],
            "edge_classes": [ec.to_dict() for ec in self.edge_classes],
            "layout_rules": [lr.to_dict() for lr in self.layout_rules],
            "generation_rules": list(self.generation_rules),
            "journey_keys": list(self.journey_keys),
            "panel_width": self.panel_width,
            "degree_offsets": [list(o) for o in self.degree_offsets],
            "function_offsets": {k: list(v) for k, v in self.function_offsets.items()},
            "hub_offset": list(self.hub_offset),
            "launch_rules": dict(self.launch_rules),
            "mode": self.mode,
        }

    @classmethod
    def from_dict(cls, d: Dict) -> "FunctionalNetworkTemplate":
        tpl = cls(
            template_id=d["template_id"],
            title=d["title"],
            description=d.get("description", ""),
            node_classes=[NodeClass(**nc) for nc in d.get("node_classes", [])],
            edge_classes=[EdgeClass(**ec) for ec in d.get("edge_classes", [])],
            layout_rules=[PanelLayoutRule(**lr) for lr in d.get("layout_rules", [])],
            generation_rules=list(d.get("generation_rules", [])),
            journey_keys=list(d.get("journey_keys", [])),
            panel_width=float(d.get("panel_width", 470.0)),
            degree_offsets=[list(o) for o in d.get("degree_offsets", [])],
            function_offsets={k: list(v)
                              for k, v in d.get("function_offsets", {}).items()},
            hub_offset=list(d.get("hub_offset", [0.0, -195.0])),
            launch_rules=dict(d.get("launch_rules", {})),
            mode=d.get("mode", "major"),
            schema=d.get("schema", SCHEMA_VERSION),
        )
        tpl.validate()
        return tpl


